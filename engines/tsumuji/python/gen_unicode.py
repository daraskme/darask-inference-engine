"""Writes crates/tsumuji-server/src/unicode_data.rs: the Unicode tables the tokenizer needs
(general categories L / M / N for the pre-tokenizer regex, and the NFC data), from Python's
unicodedata. No Rust crates, so the tables are generated once and checked in.

  python3 python/gen_unicode.py

Run in Hayate's tools shell. The Unicode version is Python's (16.0 for 3.14); the reference
tokenizer (Rust `tokenizers` with Oniguruma) may be a version or two older, which only matters
for characters assigned in between.
"""

import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "crates/tsumuji-server/src/unicode_data.rs"
MAX = 0x110000


def ranges(f):
    """Maximal runs [lo, hi] of code points with the same nonzero value f(c)."""
    out, start, cur = [], 0, 0
    for c in range(MAX + 1):
        v = f(c) if c < MAX else 0
        if v != cur:
            if cur:
                out.append((start, c - 1, cur))
            start, cur = c, v
    return out


def cat_bits(c):
    cat = unicodedata.category(chr(c))
    return {"L": 1, "M": 2, "N": 4}.get(cat[0], 0)


def main() -> int:
    cats = ranges(cat_bits)
    ccc = ranges(lambda c: unicodedata.combining(chr(c)))
    decomp, comp = [], []
    for c in range(MAX):
        if 0xAC00 <= c <= 0xD7A3:  # Hangul syllables: algorithmic
            continue
        d = unicodedata.decomposition(chr(c))
        if not d or d.startswith("<"):
            continue
        parts = [int(x, 16) for x in d.split()]
        assert len(parts) in (1, 2), (hex(c), d)
        decomp.append((c, parts[0], parts[1] if len(parts) == 2 else 0))
        # A primary composite: NFC recomposes the pair to it (excludes composition exclusions,
        # singletons and non-starter decompositions).
        if len(parts) == 2 and unicodedata.normalize("NFC", chr(parts[0]) + chr(parts[1])) == chr(c):
            comp.append((parts[0], parts[1], c))
    comp.sort()
    lines = [
        "//! Generated by python/gen_unicode.py from Python's unicodedata "
        f"(Unicode {unicodedata.unidata_version}). Do not edit.",
        "",
        "/// [lo, hi, bits]: general category L = 1, M = 2, N = 4.",
        "pub static CATS: &[(u32, u32, u8)] = &[",
        *(f"    (0x{a:X}, 0x{b:X}, {v})," for a, b, v in cats),
        "];",
        "",
        "/// [lo, hi, canonical combining class] for nonzero classes.",
        "pub static CCC: &[(u32, u32, u8)] = &[",
        *(f"    (0x{a:X}, 0x{b:X}, {v})," for a, b, v in ccc),
        "];",
        "",
        "/// Canonical decomposition mappings (one level; 0 = singleton), Hangul syllables excluded.",
        "pub static DECOMP: &[(u32, u32, u32)] = &[",
        *(f"    (0x{a:X}, 0x{b:X}, 0x{c:X})," for a, b, c in decomp),
        "];",
        "",
        "/// Primary composites: (first, second) -> composed, sorted by pair. Hangul excluded.",
        "pub static COMP: &[(u32, u32, u32)] = &[",
        *(f"    (0x{a:X}, 0x{b:X}, 0x{c:X})," for a, b, c in comp),
        "];",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"{OUT}: {len(cats)} category ranges, {len(ccc)} ccc ranges, {len(decomp)} decompositions, {len(comp)} compositions", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
